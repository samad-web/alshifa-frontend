interface HealthReportsTabProps {
    /** Optional override — when omitted, the tab resolves the calling
     *  patient's id via /api/user/me. PatientPortal calls this without props. */
    patientId?: string;
}

interface UserMe {
    patient?: { id?: string | null } | null;
}

